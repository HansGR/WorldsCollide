"""Which treasure chests a ruination seed makes available to the player.

The per-room tables are data/ruin_chests.py (generated by
tools/ruin_chest_rooms.py from the vanilla ROM). A chest id indexes
data/chests.py all_chests, so the seed's contents of chest id N are
data.chests.all_chests[N] (type, contents) once Chests.mod has run.

seed_chests(plan) answers, from the final door plan:
  - per branch, the rooms the player can reach from that branch's hub with
    the game's characters (starting party plus every character the plan
    grants) and the named keys of the rooms they reach (a fixpoint over all
    three branches: characters and keys are global progress), and the chests
    in them. A gated room (CHEST_GATES: Tzen's collapsing house) counts only
    when its check can be done with those characters.
  - per Kefka's Tower lane (A/B/C = the left/middle/right entrance), the
    tower rooms that entrance reaches on its own and their chests, and
    separately the rooms it reaches only once the switches open the gated
    crossings (switch platform, broken stairs). With -rkt the lanes come from
    the plan's tower connections; otherwise from the vanilla tower.

This is the groundwork for treasure guarantees (an item somewhere in the
seed, a money or equipment threshold, ...); nothing here changes a seed."""

from data.rooms import room_data
from data import ruin_chests as RCH
from doors.plan.ruination.kefka_tower import tower_rooms, KT_ENTRIES


def _spec_groups(rid, overrides):
    """[(elements, keys needed or None)] for a room: doors/traps/pits are open,
    each lock group needs its keys."""
    if rid in overrides:
        spec = overrides[rid]
        return [(list(spec.get('doors', ())) + list(spec.get('traps', ()))
                 + list(spec.get('pits', ())), None)]
    data = room_data.get(rid)
    if not data:
        return []
    groups = [(list(data[0]) + list(data[1]) + list(data[2]), None)]
    if len(data) >= 6 and isinstance(data[4], dict):
        for keys, items in data[4].items():
            keys = tuple(keys) if isinstance(keys, (tuple, list)) else (keys,)
            groups.append((list(items), keys))
    return groups


def _room_keys(rid):
    data = room_data.get(rid)
    return list(data[3]) if data and len(data) >= 6 else []


def _bfs(adj, start):
    seen, queue = {start}, [start]
    for cur in queue:
        for nxt in adj.get(cur, ()):
            if nxt not in seen:
                seen.add(nxt)
                queue.append(nxt)
    return seen


def game_characters(planner):
    """The starting party plus every character the plan grants."""
    chars = set(planner.config.party)
    chars.update(name for kind, name in planner.assignments.values() if kind == 'CHARACTER')
    return chars


def room_chest_ids(planner, rid, characters=None):
    """A room's chest ids; a gated room's (CHEST_GATES) only when its check can
    be done with these characters (default: the game's)."""
    check = RCH.CHEST_GATES.get(rid)
    if check is not None:
        cfg = planner.config
        chars = game_characters(planner) if characters is None else set(characters)
        locker = cfg.rewards_locked_by_character.get(check)
        owners = cfg.reward_owners.get(check)
        if ((locker is not None and locker not in chars)
                or (owners is not None and not owners & chars)):
            return []
    return list(RCH.ROOM_CHEST_IDS.get(rid, ()))


def reachable_rooms(planner, door_pairs, oneways):
    """branch id -> rooms reachable from that branch's hub (see module doc)."""
    overrides = planner.config.spec_overrides
    hub_doors = room_data['HUB50-ruin'][0]
    owner, needs = {}, {}
    for branch in planner.branches:
        for rid in sorted(branch.rooms, key=str):
            for elements, keys in _spec_groups(rid, overrides):
                for e in elements:
                    if isinstance(e, int):
                        owner.setdefault(e, rid)
                        if keys is not None:
                            needs[e] = keys
    for i, branch in enumerate(planner.branches):
        owner.setdefault(hub_doors[i], branch.hub_room)

    keychain = game_characters(planner)
    if planner.config.open_world:
        from data import ruin_constants as RC
        keychain.update(RC.ALL_CHARACTERS)
    while True:
        def open_(e):
            return set(needs.get(e, ())) <= keychain
        adj = {}
        for a, b in door_pairs:
            ra, rb = owner.get(a), owner.get(b)
            if ra is None or rb is None or not (open_(a) and open_(b)):
                continue
            adj.setdefault(ra, []).append(rb)
            adj.setdefault(rb, []).append(ra)
        for a, b in oneways:
            ra, rb = owner.get(a), owner.get(b)
            if ra is None or rb is None or not (open_(a) and open_(b)):
                continue
            adj.setdefault(ra, []).append(rb)
        reach = {i: _bfs(adj, b.hub_room) for i, b in enumerate(planner.branches)}
        keys = {k for rooms in reach.values() for r in rooms for k in _room_keys(r)}
        if keys <= keychain:
            return reach
        keychain |= keys


def _vanilla_tower_connections():
    """The vanilla tower's door pairs and one-ways (doors from exit_data; each
    trap 208N drops onto pit 308N, and KTB6's door-as-trap 1108 onto 7108)."""
    from data.map_exit_extra import exit_data
    owner = _tower_owner()
    pairs, oneways = set(), []
    for e in owner:
        partner = exit_data.get(e, [None])[0]
        if partner in owner and e < 2000:
            pairs.add(tuple(sorted((e, partner))))
        elif 2000 <= e < 3000 and e + 1000 in owner:
            oneways.append((e, e + 1000))
    oneways.append((1108, 7108))
    return sorted(pairs), oneways


def _tower_owner():
    owner = {}
    for rid in tower_rooms():
        for elements, keys in _spec_groups(rid, {}):
            if keys is None:
                for e in elements:
                    if isinstance(e, int):
                        owner.setdefault(e, rid)
    return owner


def kefka_tower_lanes(planner, door_pairs, oneways):
    """lane letter -> (rooms its entrance reaches on its own, rooms it reaches
    once the switches are pressed). With -rkt the plan's tower connections,
    otherwise the vanilla tower. The gated crossings (KT_CROSSINGS: the switch
    platform and the broken stairs) open with keys granted in other lanes' rooms
    (KT_KEY_ROOM); the tower verifier guarantees every room is reachable."""
    from doors.plan.ruination.kefka_tower import KT_CROSSINGS
    if getattr(planner, 'kt_lane_map', None) is None:
        door_pairs, oneways = _vanilla_tower_connections()
    owner = _tower_owner()
    adj = {}
    for a, b in door_pairs:
        ra, rb = owner.get(a), owner.get(b)
        if ra and rb:
            adj.setdefault(ra, []).append(rb)
            adj.setdefault(rb, []).append(ra)
    for a, b in oneways:
        ra, rb = owner.get(a), owner.get(b)
        if ra and rb:
            adj.setdefault(ra, []).append(rb)
    crossed = {room: list(nexts) for room, nexts in adj.items()}
    for ra, rb, _, two_way in KT_CROSSINGS:
        crossed.setdefault(ra, []).append(rb)
        if two_way:
            crossed.setdefault(rb, []).append(ra)
    return {entry[2]: (_bfs(adj, entry), _bfs(crossed, entry)) for entry in KT_ENTRIES}


def seed_chests(plan):
    """{'branches': {branch id: {room: [chest ids]}},
        'kefka_tower': {lane: {room: [chest ids]}},
        'kefka_tower_after_switches': {lane: {room: [chest ids]}} (rooms that lane
            reaches only once another lane's switch opens a crossing),
        'pending': [tower chest ids not yet placed in a room]}
    for a ruination DoorPlan (doors.plan.artifact.DoorPlan)."""
    planner = plan.ruination.planner
    pairs, oneways = plan.door_pairs, plan.oneways
    branches = {}
    for bid, rooms in reachable_rooms(planner, pairs, oneways).items():
        branches[bid] = {r: ids for r in sorted(rooms, key=str)
                         if (ids := room_chest_ids(planner, r))}
    tower, after_switches = {}, {}
    for lane, (own, crossed) in kefka_tower_lanes(planner, pairs, oneways).items():
        tower[lane] = {r: list(RCH.KT_ROOM_CHEST_IDS[r]) for r in sorted(own)
                       if r in RCH.KT_ROOM_CHEST_IDS}
        after_switches[lane] = {r: list(RCH.KT_ROOM_CHEST_IDS[r]) for r in sorted(crossed - own)
                                if r in RCH.KT_ROOM_CHEST_IDS}
    return {'branches': branches, 'kefka_tower': tower,
            'kefka_tower_after_switches': after_switches,
            'pending': list(RCH.KT_PENDING_CHEST_IDS)}
